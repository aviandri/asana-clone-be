import { createHash, randomUUID } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, readdir, rename, rm, stat as fsStat, statfs } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { Transform, type Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { AppError } from '../errors.js';

/** An inclusive byte range, as in `Range: bytes=start-end`. */
export type ByteRange = { start: number; end: number };

export type StoredObject = { key: string; size: number; modifiedAt: Date };

export type PutOptions = { maxBytes?: number; headBytes?: number };
export type PutResult = { size: number; sha256: string; head: Buffer };

/**
 * Where attachment bytes live (SPEC §13). Keys are opaque and generated by [newStorageKey]; they never
 * come from a filename or a request. `put` makes the object visible only once it's complete.
 */
export interface StorageDriver {
  /**
   * Stores the stream under `key`; more than `maxBytes` aborts with 413 PAYLOAD_TOO_LARGE. `head` is the
   * first `headBytes` bytes (for type sniffing without a second read).
   */
  put(key: string, stream: Readable, options?: PutOptions): Promise<PutResult>;
  get(key: string, range?: ByteRange): Readable;
  /** Missing objects are fine (deletes run after the DB commit and may repeat). */
  delete(key: string): Promise<void>;
  stat(key: string): Promise<StoredObject | null>;
  /** Every complete object, for the sweeper's orphan check. */
  list(): AsyncIterable<StoredObject>;
  /** A local file path for the object, when the driver has one (sharp reads files without buffering). */
  localPath?(key: string): string;
  /** Free space for new objects, where the driver can tell (A12). */
  freeBytes?(): Promise<number>;
  /** Removes half-written uploads older than `olderThan` (a crash mid-write), if the driver has any. */
  sweepTemps?(olderThan: Date): Promise<void>;
}

const KEY = /^[0-9a-f]{2}\/[0-9a-f]{2}\/[0-9a-f-]{36}(\.[a-z]\.webp)?$/;

/** `ab/cd/<uuid>`: random, and spread over 65,536 directories. */
export function newStorageKey(): string {
  const id = randomUUID();
  const hex = id.replace(/-/g, '');
  return `${hex.slice(0, 2)}/${hex.slice(2, 4)}/${id}`;
}

/** The key of a derived object (thumbnails: `s` small, `l` large). */
export function derivedKey(key: string, variant: 's' | 'l'): string {
  return `${key}.${variant}.webp`;
}

/** The object a key belongs to: itself, or the original for a derived key. */
export function baseKey(key: string): string {
  return key.replace(/\.[a-z]\.webp$/, '');
}

export const payloadTooLarge = (maxBytes: number) =>
  new AppError('PAYLOAD_TOO_LARGE', `Files can be at most ${Math.floor(maxBytes / (1024 * 1024))} MB`);

/** Counts, hashes and keeps the head of the bytes on their way through; over `maxBytes` fails the pipeline. */
function meter({ maxBytes = Number.MAX_SAFE_INTEGER, headBytes = 0 }: PutOptions) {
  const hash = createHash('sha256');
  const head: Buffer[] = [];
  let size = 0;
  const transform = new Transform({
    transform(chunk: Buffer, _enc, done) {
      if (size < headBytes) head.push(chunk.subarray(0, headBytes - size));
      size += chunk.length;
      if (size > maxBytes) return done(payloadTooLarge(maxBytes));
      hash.update(chunk);
      done(null, chunk);
    },
  });
  return { transform, result: (): PutResult => ({ size, sha256: hash.digest('hex'), head: Buffer.concat(head) }) };
}

/** `STORAGE_DRIVER=disk`: files under `root`; writes land in `root/.tmp` and are renamed into place. */
export class DiskStorage implements StorageDriver {
  constructor(readonly root: string) {}

  private path(key: string) {
    // Keys are ours, but a bad one must never reach the filesystem.
    if (!KEY.test(key)) throw new Error('Invalid storage key');
    return join(this.root, key);
  }

  async freeBytes() {
    await mkdir(this.root, { recursive: true });
    const s = await statfs(this.root);
    return s.bavail * s.bsize;
  }

  localPath(key: string) {
    return this.path(key);
  }

  get tmpDir() {
    return join(this.root, '.tmp');
  }

  async put(key: string, stream: Readable, options: PutOptions = {}) {
    const target = this.path(key);
    await mkdir(this.tmpDir, { recursive: true });
    const tmp = join(this.tmpDir, randomUUID());
    const { transform, result } = meter(options);
    try {
      await pipeline(stream, transform, createWriteStream(tmp, { flags: 'wx' }));
      await mkdir(dirname(target), { recursive: true });
      await rename(tmp, target);
    } catch (err) {
      await rm(tmp, { force: true });
      throw err;
    }
    return result();
  }

  get(key: string, range?: ByteRange): Readable {
    return createReadStream(this.path(key), range ? { start: range.start, end: range.end } : {});
  }

  async delete(key: string) {
    await rm(this.path(key), { force: true });
  }

  async stat(key: string) {
    try {
      const s = await fsStat(this.path(key));
      return { key, size: s.size, modifiedAt: s.mtime };
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async *list(): AsyncIterable<StoredObject> {
    let entries;
    try {
      entries = await readdir(this.root, { recursive: true, withFileTypes: true });
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return;
      throw err;
    }
    for (const entry of entries) {
      if (!entry.isFile()) continue;
      // parentPath is Node ≥ 20.12; `path` is its older name.
      const parent = (entry as { parentPath?: string }).parentPath ?? (entry as unknown as { path: string }).path;
      const key = relative(this.root, join(parent, entry.name)).split(sep).join('/');
      if (!KEY.test(key)) continue; // .tmp and anything else that isn't ours
      const s = await fsStat(join(this.root, key)).catch(() => null);
      if (s) yield { key, size: s.size, modifiedAt: s.mtime };
    }
  }

  async sweepTemps(olderThan: Date) {
    let names: string[];
    try {
      names = await readdir(this.tmpDir);
    } catch {
      return;
    }
    for (const name of names) {
      const path = join(this.tmpDir, name);
      const s = await fsStat(path).catch(() => null);
      if (s && s.mtime < olderThan) await rm(path, { force: true });
    }
  }
}
